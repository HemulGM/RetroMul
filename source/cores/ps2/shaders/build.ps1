param([string]$Out = 'D:\Work\tmp\ps2-gs-shader', [ValidateSet('All', 'LLE', 'HLE')][string]$Only = 'All')
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $Out | Out-Null

# SPIR-V words as a Pascal constant in an include file.
function Write-SpirvInclude([string]$Spv, [string]$Name, [string]$From, [string]$Include) {
  $bytes = [IO.File]::ReadAllBytes($Spv)
  $words = for ($i=0; $i -lt $bytes.Length; $i+=4) { '$' + [BitConverter]::ToUInt32($bytes,$i).ToString('X8') }
  $lines = @("// Generated by shaders/build.ps1 from $From.",
    "  ${Name}: array[0..$($words.Count-1)] of Cardinal = (")
  for ($i=0; $i -lt $words.Count; $i+=8) {
    $end=[Math]::Min($i+7,$words.Count-1)
    $suffix=','
    if ($end -eq $words.Count-1) { $suffix=');' }
    $lines += '    ' + ($words[$i..$end] -join ', ') + $suffix
  }
  [IO.File]::WriteAllText($Include, ($lines -join "`r`n")+"`r`n", [Text.UTF8Encoding]::new($false))
}

$compiler = Join-Path $env:VULKAN_SDK 'Bin\glslc.exe'
$sourceDir = Join-Path $Out 'source'
New-Item -ItemType Directory -Force $sourceDir | Out-Null
if ($Only -ne 'LLE') {
  # The HLE renderer's graphics shaders (PS2.GS.VulkanHLE).
  Get-ChildItem $PSScriptRoot -File | Where-Object { $_.Name -like 'PS2.GS.HLE*' } | ForEach-Object {
    [IO.File]::WriteAllText((Join-Path $sourceDir $_.Name), [IO.File]::ReadAllText($_.FullName), [Text.UTF8Encoding]::new($false))
  }
  # (Source file, the constant's and the include's name.)
  foreach ($stage in @(@('PS2.GS.HLE.vert', 'Vert'), @('PS2.GS.HLE.frag', 'Frag'), @('PS2.GS.HLEBlend.frag', 'BlendFrag'))) {
    $spv = Join-Path $Out "PS2.GS.HLE$($stage[1]).spv"
    & $compiler --target-env=vulkan1.1 -O "$sourceDir\$($stage[0])" -o $spv
    if ($LASTEXITCODE -ne 0) { throw "$($stage[0]) compilation failed" }
    & "$env:VULKAN_SDK\Bin\spirv-val.exe" --target-env vulkan1.1 $spv
    if ($LASTEXITCODE -ne 0) { throw "$($stage[0]) SPIR-V validation failed" }
    Write-SpirvInclude $spv "PS2HLE$($stage[1])SPIRV" $stage[0] "$PSScriptRoot\PS2.GS.HLE$($stage[1]).inc"
  }
  if ($Only -eq 'HLE') { return }
}
# Share the documented GS swizzle tables with the software implementation.
$memory = [IO.File]::ReadAllText("$PSScriptRoot\..\PS2.GS.Memory.pas")
$tables = @('// Generated from PS2.GS.Memory.pas by shaders/build.ps1.')
foreach ($name in 'Block16','Block16S','Column16','Column8','Column4') {
  $match = [regex]::Match($memory, '(?s)\b' + $name + ':.*?=\s*\((.*?)\);')
  if (!$match.Success) { throw "Missing GS table $name" }
  $values = @([regex]::Matches($match.Groups[1].Value, '\d+') | ForEach-Object Value)
  $tables += "const uint gs$name[$($values.Count)] = uint[$($values.Count)](" + ($values -join ',') + ');'
}
[IO.File]::WriteAllText("$PSScriptRoot\PS2.GS.Tables.glsl", ($tables -join "`n")+"`n", [Text.UTF8Encoding]::new($false))
$compiler = Join-Path $env:VULKAN_SDK 'Bin\glslc.exe'
# glslc rejects a UTF-8 BOM before #version. Normalize a source mirror in
# the build directory, including headers, without depending on editor encoding.
$sourceDir = Join-Path $Out 'source'
New-Item -ItemType Directory -Force $sourceDir | Out-Null
Get-ChildItem $PSScriptRoot -File | Where-Object { $_.Extension -in '.comp','.glsl' } | ForEach-Object {
  [IO.File]::WriteAllText((Join-Path $sourceDir $_.Name), [IO.File]::ReadAllText($_.FullName), [Text.UTF8Encoding]::new($false))
}
foreach ($kind in 'Sprite','Triangle') {
  $spv = Join-Path $Out "PS2.GS.$kind.spv"
  $optimization = if ($kind -eq 'Triangle') { '-O0' } else { '-O' }
  & $compiler --target-env=vulkan1.1 $optimization "$sourceDir\PS2.GS.$kind.comp" -o $spv
  if ($LASTEXITCODE -ne 0) { throw "$kind shader compilation failed" }
  if ($kind -eq 'Triangle') {
    # These execution modes are only used when TVulkanCompute.ExactDouble
    # reports support. Add them before optimization, so transformations must
    # retain IEEE RTE, denormals and signed zeros in 32/64-bit operations.
    $asm = Join-Path $Out 'triangle.spvasm'
    & "$env:VULKAN_SDK\Bin\spirv-dis.exe" $spv -o $asm
    if ($LASTEXITCODE -ne 0) { throw 'SPIR-V disassembly failed' }
    $source = [IO.File]::ReadAllLines($asm)
    $entry = [regex]::Match(($source -join "`n"), 'OpEntryPoint GLCompute (%\S+)').Groups[1].Value
    $lastCapability = 0
    for ($i=0; $i -lt $source.Length; $i++) {
      if ($source[$i].TrimStart().StartsWith('OpCapability ')) { $lastCapability=$i }
    }
    $text = [Collections.Generic.List[string]]::new()
    for ($i=0; $i -lt $source.Length; $i++) {
      $text.Add($source[$i])
      if ($i -eq $lastCapability) {
        $text.Add('OpCapability DenormPreserve')
        $text.Add('OpCapability SignedZeroInfNanPreserve')
        $text.Add('OpCapability RoundingModeRTE')
        $text.Add('OpExtension "SPV_KHR_float_controls"')
      }
      if ($source[$i] -match 'OpExecutionMode .* LocalSize') {
        foreach ($width in 32,64) {
          foreach ($mode in 'DenormPreserve','SignedZeroInfNanPreserve','RoundingModeRTE') {
            $text.Add("OpExecutionMode $entry $mode $width")
          }
        }
      }
    }
    [IO.File]::WriteAllLines($asm, $text, [Text.UTF8Encoding]::new($false))
    & "$env:VULKAN_SDK\Bin\spirv-as.exe" --target-env vulkan1.1 $asm -o $spv
    if ($LASTEXITCODE -ne 0) { throw 'SPIR-V float-control assembly failed' }
    & "$env:VULKAN_SDK\Bin\spirv-opt.exe" --target-env=vulkan1.1 -O $spv -o $spv
    if ($LASTEXITCODE -ne 0) { throw 'SPIR-V optimization failed' }
  }
  & "$env:VULKAN_SDK\Bin\spirv-val.exe" --target-env vulkan1.1 $spv
  if ($LASTEXITCODE -ne 0) { throw "$kind SPIR-V validation failed" }
  $bytes = [IO.File]::ReadAllBytes($spv)
  $words = for ($i=0; $i -lt $bytes.Length; $i+=4) { '$' + [BitConverter]::ToUInt32($bytes,$i).ToString('X8') }
  $lines = @("// Generated by shaders/build.ps1 from PS2.GS.$kind.comp.",
    "  PS2${kind}SPIRV: array[0..$($words.Count-1)] of Cardinal = (")
  for ($i=0; $i -lt $words.Count; $i+=8) {
    $end=[Math]::Min($i+7,$words.Count-1)
    $suffix=','
    if ($end -eq $words.Count-1) { $suffix=');' }
    $lines += '    ' + ($words[$i..$end] -join ', ') + $suffix
  }
  [IO.File]::WriteAllText("$PSScriptRoot\PS2.GS.$kind.inc", ($lines -join "`r`n")+"`r`n", [Text.UTF8Encoding]::new($false))
}
