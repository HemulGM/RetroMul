param([string]$Out = 'D:\Work\tmp\ps2-gs-shader')
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $Out | Out-Null
$compiler = Join-Path $env:VULKAN_SDK 'Bin\glslc.exe'
$spv = Join-Path $Out 'PS2.GS.Sprite.spv'
& $compiler --target-env=vulkan1.1 -O "$PSScriptRoot\PS2.GS.Sprite.comp" -o $spv
if ($LASTEXITCODE -ne 0) { throw 'shader compilation failed' }
$bytes = [IO.File]::ReadAllBytes($spv)
$words = for ($i=0; $i -lt $bytes.Length; $i+=4) { '$' + [BitConverter]::ToUInt32($bytes,$i).ToString('X8') }
$lines = @('// Generated by shaders/build.ps1 from PS2.GS.Sprite.comp.',
  "  PS2SpriteSPIRV: array[0..$($words.Count-1)] of Cardinal = (")
for ($i=0; $i -lt $words.Count; $i+=8) {
  $end=[Math]::Min($i+7,$words.Count-1)
  $suffix=','
  if ($end -eq $words.Count-1) { $suffix=');' }
  $lines += '    ' + ($words[$i..$end] -join ', ') + $suffix
}
[IO.File]::WriteAllText("$PSScriptRoot\PS2.GS.Sprite.inc", ($lines -join "`r`n")+"`r`n", [Text.UTF8Encoding]::new($false))
